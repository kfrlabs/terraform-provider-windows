// Package winclient: shared JSON envelope parsing for PowerShell scripts.
//
// Every resource script wraps its result in the same Emit-OK/Emit-Err
// envelope (see CLAUDE.md), but before this helper each client reimplemented
// the same pipeline: run the script, classify a context error, classify a
// transport error, locate the last JSON line, unmarshal it and surface an
// Emit-Err kind. Behaviour then drifted between resources (custom timeout
// hints, different context keys) and every protocol fix had to be replicated
// by hand (issue #178).
//
// runEnvelope centralises that pipeline. Resource clients keep their typed
// error kinds and message hints, but no longer own the parsing rules.
package winclient

import (
	"context"
	"encoding/json"
	"fmt"
)

// Envelope is the JSON object produced by the Emit-OK/Emit-Err helpers.
// Every winclient script emits exactly these fields, so resources can share
// one representation instead of declaring identical structs.
type Envelope struct {
	OK      bool              `json:"ok"`
	Kind    string            `json:"kind,omitempty"`
	Message string            `json:"message,omitempty"`
	Context map[string]string `json:"context,omitempty"`
	Data    json.RawMessage   `json:"data,omitempty"`
}

// EnvelopeStage identifies where envelope processing failed.
type EnvelopeStage string

const (
	// EnvelopeStageTimeout means the call was cancelled or its deadline
	// expired. The script's outcome is unknown, so the caller must not retry
	// it. Cause is the context error.
	EnvelopeStageTimeout EnvelopeStage = "timeout"
	// EnvelopeStageTransport means the SSH/PowerShell call itself failed.
	// Cause carries the transport error.
	EnvelopeStageTransport EnvelopeStage = "transport"
	// EnvelopeStageNoEnvelope means stdout contained no JSON envelope at all.
	EnvelopeStageNoEnvelope EnvelopeStage = "no_envelope"
	// EnvelopeStageInvalidJSON means the envelope line could not be decoded.
	// Cause carries the JSON error.
	EnvelopeStageInvalidJSON EnvelopeStage = "invalid_json"
	// EnvelopeStageRemote means the script ran to completion and emitted an
	// Emit-Err envelope: the target rejected the operation. RemoteKind is the
	// script-side kind string; the resource maps it to its typed kind.
	EnvelopeStageRemote EnvelopeStage = "remote"
)

// EnvelopeError describes a failed runEnvelope call. It is deliberately
// resource-neutral: each client converts it to its own typed error so that
// errors.As/errors.Is keep working for callers and tests.
type EnvelopeError struct {
	// Stage is the failed stage of the pipeline.
	Stage EnvelopeStage
	// Operation is the caller-supplied operation name (e.g. "read").
	Operation string
	// RemoteKind is the raw Emit-Err kind for EnvelopeStageRemote.
	RemoteKind string
	// Message is the human-readable message. For remote failures it is the
	// script's own message; otherwise it is generated by runEnvelope.
	Message string
	// Context holds the diagnostic context, already including Operation and
	// any caller-provided base context. Callers may enrich it with
	// resource-specific hints before returning their typed error.
	Context map[string]string
	// Cause is the underlying error, when there is one.
	Cause error
}

// Error implements the error interface.
func (e *EnvelopeError) Error() string {
	if e.Cause != nil {
		return fmt.Sprintf("winclient: %s: %s: %v", e.Operation, e.Message, e.Cause)
	}
	return fmt.Sprintf("winclient: %s: %s", e.Operation, e.Message)
}

// Unwrap returns the underlying cause.
func (e *EnvelopeError) Unwrap() error { return e.Cause }

// EnvelopeRunner executes one PowerShell script and returns its stdout,
// stderr and transport error. Clients pass a closure around their
// test-substitutable runner (e.g. runDirectoryPowerShell) so the helper does
// not bypass the existing seams.
type EnvelopeRunner func(ctx context.Context, script, stdin string) (stdout, stderr string, err error)

// runEnvelope executes script through run and parses the trailing JSON
// envelope. stdin is forwarded to run for scripts that consume secrets.
//
// baseContext is copied, never mutated, and its keys take precedence over
// values emitted by the script: operation and host identity come from the
// client, not from the target. The returned Envelope is non-nil for remote
// (Emit-Err) failures so callers can still inspect data or context, matching
// the previous per-resource behaviour.
func runEnvelope(
	ctx context.Context,
	run EnvelopeRunner,
	op, script, stdin string,
	baseContext map[string]string,
) (*Envelope, *EnvelopeError) {
	if run == nil {
		return nil, &EnvelopeError{
			Stage:     EnvelopeStageTransport,
			Operation: op,
			Message:   fmt.Sprintf("SSH transport error during %q", op),
			Context:   envelopeContext(baseContext, op, nil),
			Cause:     fmt.Errorf("winclient: nil envelope runner"),
		}
	}

	stdout, stderr, err := run(ctx, script, stdin)
	if err != nil {
		if ctxErr := ctx.Err(); ctxErr != nil {
			return nil, &EnvelopeError{
				Stage:     EnvelopeStageTimeout,
				Operation: op,
				Message:   fmt.Sprintf("operation %q timed out or was cancelled", op),
				Context:   envelopeContext(baseContext, op, nil),
				Cause:     ctxErr,
			}
		}
		return nil, &EnvelopeError{
			Stage:     EnvelopeStageTransport,
			Operation: op,
			Message:   fmt.Sprintf("SSH transport error during %q", op),
			Context: envelopeContext(baseContext, op, map[string]string{
				"stderr": truncate(stderr, 2048),
				"stdout": truncate(stdout, 2048),
			}),
			Cause: err,
		}
	}

	line := extractLastJSONLine(stdout)
	if line == "" {
		return nil, &EnvelopeError{
			Stage:     EnvelopeStageNoEnvelope,
			Operation: op,
			Message:   fmt.Sprintf("no JSON envelope returned from %q", op),
			Context: envelopeContext(baseContext, op, map[string]string{
				"stderr": truncate(stderr, 2048),
				"stdout": truncate(stdout, 2048),
			}),
		}
	}

	var resp Envelope
	if jerr := json.Unmarshal([]byte(line), &resp); jerr != nil {
		return nil, &EnvelopeError{
			Stage:     EnvelopeStageInvalidJSON,
			Operation: op,
			Message:   fmt.Sprintf("invalid JSON envelope from %q", op),
			Context: envelopeContext(baseContext, op, map[string]string{
				"stdout": truncate(stdout, 2048),
			}),
			Cause: jerr,
		}
	}

	if !resp.OK {
		// Start from the script's context so target-provided diagnostics
		// survive, then overlay the client's authoritative keys.
		remote := make(map[string]string, len(resp.Context)+len(baseContext)+1)
		for k, v := range resp.Context {
			remote[k] = v
		}
		return &resp, &EnvelopeError{
			Stage:      EnvelopeStageRemote,
			Operation:  op,
			RemoteKind: resp.Kind,
			Message:    resp.Message,
			Context:    envelopeContext(remote, op, baseContext),
		}
	}
	return &resp, nil
}

// envelopeContext builds a fresh diagnostic map: base entries first, then
// extra entries, with operation last so it can never be shadowed by a
// script-supplied value.
func envelopeContext(base map[string]string, op string, extra map[string]string) map[string]string {
	out := make(map[string]string, len(base)+len(extra)+1)
	for k, v := range base {
		out[k] = v
	}
	for k, v := range extra {
		out[k] = v
	}
	out["operation"] = op
	return out
}
